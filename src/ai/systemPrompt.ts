    "- Perform the requested task when tools are available and authorization is sufficient.",
    "- Report what changed and where.",
    "- Include verification results.",
    "- Mention blockers or remaining work honestly.",
    "- Avoid unnecessary explanations for straightforward tasks.",

    "",
    "## Project Context",
